"""
Регенерирует два новых файла контента:
  game-docs/src/content/mech_research.json
  game-docs/src/content/mech_multiplayer.json

Это единственный разрешённый способ их править: генератор держит текст в
переносимых строках и не даёт сломать JSON кавычками (см. AGENT-GUIDE, А.3).
Запуск:  python3 game-docs/tools/author_mech_new.py
"""
import io
import json
import os
import datetime

OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "src", "content")
NL = chr(10)  # реальный перевод строки: json.dumps сам превратит его в \n (chr(92)+"n" дублировал экранирование)


def H(t):        return {"type": "h", "text": t}
def P(*t):       return {"type": "p", "text": list(t)}
def NOTE(t):     return {"type": "note", "text": t}
def L(*items, ordered=False): return {"type": "list", "ordered": ordered, "items": list(items)}
def TODO(*items): return {"type": "todo", "items": [{"text": t, "done": False} for t in items]}
def KV(head, *rows): return {"type": "kv", "head": list(head), "rows": [list(r) for r in rows]}
def CODE(lang, *lines): return {"type": "code", "lang": lang, "code": NL.join(lines)}


def doc(tid, title, subtitle, blocks, status="wip"):
    return {
        "id": tid,
        "kind": "mechanics",
        "title": title,
        "subtitle": subtitle,
        "status": status,
        "updated": datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "blocks": blocks,
    }


def write(name, d):
    path = os.path.join(OUT, name)
    txt = json.dumps(d, ensure_ascii=False, indent=2) + chr(10)
    io.open(path, "w", encoding="utf-8").write(txt)
    print("%s: блоков %d · байт %d" % (name, len(d["blocks"]), len(txt.encode("utf-8"))))


