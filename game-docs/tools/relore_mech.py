LEFTOVER = re.compile(r"остров|Ветряной|Горечь|горьк|Серов|\bМарк\b|Дорн|Чайк|Patrol|школ|вертол|катер|питомник|Тюлень|Dokera|Патруль", re.I)


def canon(b):
    t = b.get("type")
    if t in ("h", "note"):
        return b.get("text") or ""
    if t == "p":
        return NL.join(b.get("text") or [])
    if t == "list":
        return NL.join(b.get("items") or [])
    if t == "todo":
        return NL.join(s.get("text", "") for s in b.get("items") or [])
    if t == "kv":
        return " | ".join(b.get("head") or [])
    return ""


def settext(b, text):
    t = b["type"]
    if t in ("h", "note"):
        b["text"] = text
    elif t == "p":
        b["text"] = text.split(NL)
    elif t == "list":
        b["items"] = text.split(NL)
    elif t == "todo":
        old = b.get("items") or [{}]
        b["items"] = [{"text": s, "done": (old[i].get("done") if i < len(old) else False)}
                      for i, s in enumerate(text.split(NL))]


def norm(s):
    return re.sub(r"\s+", " ", (s or "").replace("\\n", NL).strip())


def sub_all(obj):
    """Глобальные замены во всех строках структуры, с возвратом числа замен."""
    n = 0
    if isinstance(obj, dict):
        for k in list(obj):
            if isinstance(obj[k], str):
                s = obj[k]
                for a, c in GLOBAL:
                    if a in s:
                        s = s.replace(a, c)
                        n += 1
                if s != obj[k]:
                    obj[k] = s
            else:
                n += sub_all(obj[k])
    elif isinstance(obj, list):
        for i, v in enumerate(obj):
            if isinstance(v, str):
                s = v
                for a, c in GLOBAL:
                    if a in s:
                        s = s.replace(a, c)
                        n += 1
                if s != v:
                    obj[i] = s
            else:
                n += sub_all(v)
    return n


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="только отчёт, ничего не писать")
    ap.add_argument("--review", action="store_true", help="печать текста изменённых блоков")
    args = ap.parse_args()

    stats = {"exact": 0, "kv": 0, "global": 0, "files": 0}
    misses = []
    for fname in sorted(os.listdir(CONTENT)):
        if not fname.startswith("mech_") or not fname.endswith(".json") or fname in SKIP:
            continue
        path = os.path.join(CONTENT, fname)
        d = json.load(io.open(path, encoding="utf-8"))
        before = json.dumps(d, ensure_ascii=False)
        blocks = d.get("blocks") or []
        changed = []

        for (typ, needle, new) in REWRITE.get(fname, []):
            hit = None
            for i, b in enumerate(blocks):
                if b.get("type") == typ and norm(needle) in norm(canon(b)):
                    hit = i
                    break
            if hit is None:
                misses.append((fname, needle[:40]))
                continue
            old = canon(blocks[hit])
            settext(blocks[hit], new)
            stats["exact"] += 1
            changed.append((hit, blocks[hit]["type"], old, new))

        if fname in META:
            d.update(META[fname])          # заголовок/подзаголовок вкладки — тоже часть лора
        spec = KV.get(fname)
        if spec:
            if spec.get("note"):
                for b in blocks:
                    if b.get("type") == "note":
                        b["text"] = spec["note"]
                        stats["kv"] += 1
                        break
            for i, b in enumerate(blocks):
                if b.get("type") != "kv" or not b.get("head"):
                    continue
                key = b["head"][0]
                if key in spec:
                    head, rows = spec[key]
                    old = " | ".join(b["head"]) + " :: " + NL.join(" / ".join(r) for r in b.get("rows") or [])[:200]
                    b["head"], b["rows"] = head, [list(r) for r in rows]
                    stats["kv"] += 1
                    changed.append((i, "kv", old, " | ".join(head)))

        stats["global"] += sub_all(d)          # и по полям title/subtitle тоже

        after = json.dumps(d, ensure_ascii=False)
        tag = "без изменений" if after == before else ("кандидат" if args.check else "записан")
        if after != before and not args.check:
            d["updated"] = datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
            io.open(path, "w", encoding="utf-8").write(json.dumps(d, ensure_ascii=False, indent=2) + NL)
        if after != before:
            stats["files"] += 1
        left = sorted(set(m.group(0) for m in LEFTOVER.finditer(after)))
        print("%-26s %-12s правок: %2d | старое слово осталось: %s"
              % (fname, tag, len(changed) + 0, ", ".join(left) or "нет"))
        if args.review:
            for i, ty, old, new in changed:
                print("   --- [%02d %s]" % (i, ty))
                print("   было: " + old.replace(NL, NL + "         "))
                print("   стало: " + new.replace(NL, NL + "         "))

    if misses:
        print(chr(10) + "НЕ НАЙДЕНО якорей (возможно, уже применено):")
        for f, n in misses:
            print("   %-24s %s" % (f, n))
    print(chr(10) + "итог: точечных %d · таблиц %d · глобальных замен %d · файлов %d"
          % (stats["exact"], stats["kv"], stats["global"], stats["files"]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
